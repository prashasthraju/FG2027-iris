#!/usr/bin/env bash
# Regenerate paper_gen/ (every macro and table body the paper prints) from the shipped result files in a temporary copy and diff it against the shipped paper_gen/.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
tmp="$(mktemp -d)"
cp -r "$here/tools" "$here/outputs" "$here/paper_gen" "$tmp/"
rm -f "$tmp"/paper_gen/*.tex
(cd "$tmp" && python tools/paper_numbers.py > /dev/null)
if diff -r "$tmp/paper_gen" "$here/paper_gen" > /dev/null; then
  echo "ok   paper_gen/ regenerated byte-identically from outputs/ ($(ls "$tmp/paper_gen" | wc -l) files)"
else
  diff -r "$tmp/paper_gen" "$here/paper_gen" | head -20
  echo "FAIL paper_gen/ differs"; exit 1
fi
