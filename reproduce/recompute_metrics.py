"""Tier 1: recompute the headline numbers independently from the shipped scalar scores and verdicts, and compare them with the paper's macros.

    python reproduce/recompute_metrics.py

Inputs (no images, no embeddings):
  outputs/scores_liveportrait.json            per session, the mean ArcIris angular distance from the video to each of the 67 enrolled proxies
  outputs/proxy_attr_issuer_results.json      the issuer-side verdicts of every session, variant and claim
  paper_gen/numbers.tex                       the macros the paper prints (generated by tools/paper_numbers.py)
This script does not import the evaluation code: T1, ROC, EER, AUC, TAR, rank-1 and the verdict counts are recomputed here from the raw scores and rows.
"""
import json
import re
import sys
from pathlib import Path

import numpy as np
from sklearn.metrics import roc_auc_score, roc_curve

ROOT = Path(__file__).resolve().parent.parent
S = json.loads((ROOT / "outputs" / "scores_liveportrait.json").read_text())
R = json.loads((ROOT / "outputs" / "proxy_attr_issuer_results.json").read_text())
MAC = dict(re.findall(r"\\newcommand\{\\(\w+)\}\{([^}]*)\}", (ROOT / "paper_gen" / "numbers.tex").read_text()))

fails = []


def check(name, got, macro, tol=0.0):
    want = MAC[macro]
    try:
        ok = abs(float(got) - float(want)) <= tol
    except ValueError:
        ok = str(got) == want
    print(("ok   " if ok else "FAIL ") + f"{name:46s} recomputed {got!s:>12}   paper {want}")
    if not ok:
        fails.append(name)


def split(sessions):
    gen, imp, per = [], [], []
    for s in sessions:
        d = np.array([np.nan if x is None else x for x in s["distance"]])
        k = s["driver_proxy"]
        others = np.delete(d, k)
        others = others[np.isfinite(others)]
        if np.isfinite(d[k]):
            gen.append(d[k])
        imp += others.tolist()
        per.append((d, k))
    return np.array(gen), np.array(imp), per


tuning = [s for s in S["sessions"] if s["tuning"]]
test = [s for s in S["sessions"] if not s["tuning"]]

# T1: the 1% quantile of the distances to the OTHER enrolled proxies on the 15 tuning sessions. It was frozen when only the first people were enrolled
# (outputs/proxy_attr_plan.json), so its impostors are the other proxies of that first plan, not of the final 67-proxy ledger.
frozen = {v["did"] for v in json.loads((ROOT / "outputs" / "proxy_attr_plan.json").read_text())["enrolment"].values()} & set(S["proxies"])
freeze_idx = [i for i, n in enumerate(S["proxies"]) if n in frozen]
imp_t = [x for s in tuning for i, x in enumerate(s["distance"]) if x is not None and i in freeze_idx and i != s["driver_proxy"]]
T1 = float(np.quantile(imp_t, 0.01))
print(f"tuning sessions {len(tuning)}, proxies enrolled when T1 was frozen {len(freeze_idx)}, tuning impostor comparisons {len(imp_t)}, test sessions {len(test)}")
check("T1 (1% quantile of tuning impostors)", round(T1, 4), "Tone", tol=2e-3)
check("proxies enrolled when T1 was frozen", len(freeze_idx), "nFreezeProxies")
check("tuning impostor comparisons", len(imp_t), "nTuningImp")

gen, imp, per = split(test)
y = np.r_[np.ones(len(gen)), np.zeros(len(imp))]
sc = -np.r_[gen, imp]
fpr, tpr, _ = roc_curve(y, sc)
i = int(np.argmin(np.abs((1 - tpr) - fpr)))
check("ArcIris EER (%)", round(100 * (fpr[i] + 1 - tpr[i]) / 2, 2), "eer", tol=0.01)
check("ArcIris AUC (%)", round(100 * roc_auc_score(y, sc), 2), "auc", tol=0.01)
check("ArcIris TAR at 1% FAR (%)", round(100 * np.interp(1e-2, fpr, tpr), 2), "tar", tol=0.01)
check("test impostor comparisons", len(imp), "nImpostors")
check("rank-1 (driver's proxy nearest of 67)", sum(int(np.isfinite(d).any() and np.nanargmin(d) == k) for d, k in per), "rankOneK")
check("sessions in the separation test", len(test), "rankOneN")
dist_ok = sum(int(np.isfinite(d[k]) and d[k] < float(MAC["Tone"])) for d, k in per)
check("genuine accepted by distance at the frozen T1", f"{dist_ok}/{len(test)}", "distAcc")
imp_ok = sum(int(x < float(MAC["Tone"])) for x in imp)
check("impostor comparisons accepted at the frozen T1", f"{imp_ok}/{len(imp)}", "impAcc")

# verdicts of the full protocol (issuer-side rows): LivePortrait, test split
rows = [r for r in R["rows"] if not r["tuning"] and r.get("generator", "liveportrait") == "liveportrait"]
honest = [r for r in rows if r["variant"] == "original" and r["kind"] in ("self", "cross")]
attributed = [r for r in honest if r["outcome"] in ("SELF", "CROSS")]
wrong = [r for r in attributed if r.get("driver") != r.get("truth_driver")]
check("honest test sessions", len(honest), "nTest")
check("attributed to the right driver", len(attributed) - len(wrong), "kCorrect")
check("attributed to a wrong driver", len(wrong), "nWrong")
claims = [c for c in R["claims"] if not c["tuning"]]
check("false claims made", len(claims), "nFalse")
check("false claims accepted", sum(c["outcome"] in ("SELF", "CROSS") for c in claims), "nFalseAccepted")
stolen = [c for c in claims if c["claim"] == "driver's key, another person's iris"]
check("stolen-key claims", len(stolen), "nStolenKey")
twins = [r for r in rows if r["variant"] == "raw_twin" and r["kind"] in ("self", "cross")]
check("un-embedded copies tested", len(twins), "nTwin")
print("     un-embedded copies attributed by the full verifier:", sum(r["outcome"] in ("SELF", "CROSS") for r in twins), "(paper: 0)")

# colour-matched variant: paired acceptance at the frozen T1 from the per-session distances of outputs/colour_match/results.json
CM = json.loads((ROOT / "outputs" / "colour_match" / "results.json").read_text())["attribution"]["per_session"]
T1f = float(MAC["Tone"])
dn = [v["donor"] < T1f for v in CM.values()]
tg = [v["target"] < T1f for v in CM.values()]
check("colour match: sessions", len(CM), "cmN")
check("colour match: donor colour accepted", sum(dn), "cmAccDonor")
check("colour match: target colour accepted", sum(tg), "cmAccTarget")
check("colour match: accepted only in donor colour", sum(d and not t for d, t in zip(dn, tg)), "cmOnlyDonor")
check("colour match: accepted only in target colour", sum(t and not d for d, t in zip(dn, tg)), "cmOnlyTarget")

print("\nAll recomputed numbers match the paper's macros." if not fails else f"\n{len(fails)} MISMATCH(ES): {fails}")
sys.exit(1 if fails else 0)
